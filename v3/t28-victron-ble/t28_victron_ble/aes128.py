_RCON = (0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)


def _xtime(value: int) -> int:
    value <<= 1
    if value & 0x100:
        value ^= 0x11B
    return value


def _expand_key(key: bytes) -> list[int]:
    if len(key) != 16:
        raise ValueError("AES-128 key must be 16 bytes")
    words = list(key)
    for index in range(4, 44):
        temp = words[(index - 1) * 4 : index * 4]
        if index % 4 == 0:
            temp = [temp[1], temp[2], temp[3], temp[0]]
            temp = [_SBOX[byte] for byte in temp]
            temp[0] ^= _RCON[index // 4]
        words.extend(words[(index - 4) * 4 + offset] ^ temp[offset] for offset in range(4))
    return words


def encrypt_block(key: bytes, block: bytes) -> bytes:
    if len(block) != 16:
        raise ValueError("AES block must be 16 bytes")
    schedule = _expand_key(key)
    state = [block[index] ^ schedule[index] for index in range(16)]
    for round_index in range(1, 10):
        state = [_SBOX[byte] for byte in state]
        state = [
            state[0], state[5], state[10], state[15],
            state[4], state[9], state[14], state[3],
            state[8], state[13], state[2], state[7],
            state[12], state[1], state[6], state[11],
        ]
        mixed = [0] * 16
        for column in range(4):
            base = column * 4
            s0, s1, s2, s3 = state[base : base + 4]
            mixed[base] = _xtime(s0) ^ _xtime(s1) ^ s1 ^ s2 ^ s3
            mixed[base + 1] = s0 ^ _xtime(s1) ^ _xtime(s2) ^ s2 ^ s3
            mixed[base + 2] = s0 ^ s1 ^ _xtime(s2) ^ _xtime(s3) ^ s3
            mixed[base + 3] = _xtime(s0) ^ s0 ^ s1 ^ s2 ^ _xtime(s3)
        offset = round_index * 16
        state = [mixed[index] ^ schedule[offset + index] for index in range(16)]
    state = [_SBOX[byte] for byte in state]
    state = [
        state[0], state[5], state[10], state[15],
        state[4], state[9], state[14], state[3],
        state[8], state[13], state[2], state[7],
        state[12], state[1], state[6], state[11],
    ]
    state = [state[index] ^ schedule[160 + index] for index in range(16)]
    return bytes(state)


def aes128_ctr(key: bytes, counter: bytes, data: bytes, *, little_endian: bool = True) -> bytes:
    """XOR *data* with the AES-128-CTR keystream starting at *counter* (16 bytes)."""
    if len(counter) != 16:
        raise ValueError("CTR counter must be 16 bytes")
    endian = "little" if little_endian else "big"
    value = int.from_bytes(counter, endian)
    output = bytearray()
    for offset in range(0, len(data), 16):
        keystream = encrypt_block(key, value.to_bytes(16, endian))
        chunk = data[offset : offset + 16]
        output.extend(chunk[index] ^ keystream[index] for index in range(len(chunk)))
        value = (value + 1) & ((1 << 128) - 1)
    return bytes(output)


def victron_ctr_decrypt(key: bytes, nonce: int, ciphertext: bytes) -> bytes:
    """Decrypt Victron Extra Manufacturer Data using the published AES-128-CTR construction."""
    if not 0 <= nonce <= 0xFFFF:
        raise ValueError("Victron nonce must be a 16-bit value")
    counter = nonce.to_bytes(2, "little") + bytes(14)
    return aes128_ctr(key, counter, ciphertext, little_endian=True)
